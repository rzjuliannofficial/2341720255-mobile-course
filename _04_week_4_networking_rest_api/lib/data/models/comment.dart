/// Model entity Comment yang merepresentasikan data komentar
/// dari endpoint JSONPlaceholder GET /comments?postId={id}.
class Comment {
  const Comment({
    required this.postId,
    required this.id,
    required this.name,
    required this.email,
    required this.body,
  });

  final int postId;
  final int id;
  final String name;
  final String email;
  final String body;

  /// Factory fromJson yang aman terhadap null dan tipe dinamis (null-safe parsing).
  /// Menggunakan fallback default yang aman untuk mencegah runtime cast exception
  /// jika API mengembalikan field yang hilang atau null.
  factory Comment.fromJson(Map<String, dynamic> json) {
    return Comment(
      postId: (json['postId'] as num?)?.toInt() ?? 0,
      id: (json['id'] as num?)?.toInt() ?? 0,
      name: json['name'] as String? ?? '',
      email: json['email'] as String? ?? '',
      body: json['body'] as String? ?? '',
    );
  }

  /// Serialisasi Comment ke JSON Map.
  Map<String, dynamic> toJson() => {
        'postId': postId,
        'id': id,
        'name': name,
        'email': email,
        'body': body,
      };
}
